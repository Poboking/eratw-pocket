#!/usr/bin/env python
"""``inspect_apk.py`` 的清单 <-> 随包对账回归（CMP-74）。

用法（在 eratw-android 下）::

    python tools/apkpack/test_inspect_apk.py

不依赖 Gradle / Android SDK：直接合成一个最小 APK（zip），覆盖两条打包形态：

- 单条：``program.erbc`` + ``program.meta`` + ``program.stmt.idx``；
- 分片：``program.partNNN.erbc`` ×3 + ``program.parts``（两列，设备侧现行契约）+ 两个侧车。

每条用例调 ``inspect_apk.check(...)`` 拿 ``Report``，断言 FAIL 面：

- 绿：两种形态都 0 个 FAIL；
- 红：包里多一个清单没登记的文件 / 清单的 ``manifest-sha256`` 对不上 /
  分片 sha 被改坏 / 旧格式清单在 ``--require-bundled`` 下必须被判红。

退出码：0 = 全部通过，1 = 有断言失败。
"""

from __future__ import annotations

import hashlib
import importlib.util
import sys
import tempfile
import zipfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("inspect_apk", HERE / "inspect_apk.py")
assert spec is not None and spec.loader is not None
inspect_apk = importlib.util.module_from_spec(spec)
spec.loader.exec_module(inspect_apk)

ASSET = "assets/erbc.v1/"


def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def manifest_text(
    *,
    container: bytes,
    meta: bytes,
    stmt_idx: bytes,
    parts: list[tuple[str, bytes]] | None,
    shard_sha_override: str | None = None,
    drop: set[str] | None = None,
    legacy: bool = False,
) -> str:
    """按 app/build.gradle.kts 的格式拼清单；`drop` 模拟「清单漏登记」。"""
    drop = drop or set()
    lines: list[str] = ["# generated by test_inspect_apk.py"]
    if not legacy:
        lines.append("manifest-format 2")
    lines += [
        "format-version 2",
        "container-magic ERBC",
        "container-version 2",
        "erbcc 0.1.0-SNAPSHOT",
        "build-mode full",
        "corpus-root /tmp/corpus",
        "source-files 0",
    ]
    build_artifacts = [
        ("erbc.v1/program.erbc", container),
        ("erbc.v1/program.meta", meta),
        ("erbc.v1/program.stmt.idx", stmt_idx),
    ]
    lines.append(f"artifacts {len(build_artifacts)}")
    for rel, data in build_artifacts:
        lines.append(f"artifact {rel} {len(data)} {sha(data)}")

    if legacy:
        # 旧打包脚本：只有构建清单，没有 package 段，也没有 manifest-format。
        return "\n".join(lines) + "\n"

    physical: list[tuple[str, bytes]] = []
    if parts is not None:
        physical += [(ASSET + name, data) for name, data in parts]
        physical.append((ASSET + "program.parts", b""))   # 占位，真实字节由调用方覆盖
    else:
        physical.append((ASSET + "program.erbc", container))
    physical += [(ASSET + "program.meta", meta), (ASSET + "program.stmt.idx", stmt_idx)]

    package_rows = [(rel, data) for rel, data in physical if rel[len(ASSET):] not in drop]
    lines.append("manifest-source package")
    lines.append(f"package-artifacts {len(package_rows)}")
    for rel, data in package_rows:
        lines.append(f"package-artifact {rel[len('assets/'):]} {len(data)} {sha(data)}")
    lines.append(f"container-artifact erbc.v1/program.erbc {len(container)} {sha(container)}")
    shards = parts or []
    lines.append(f"container-shards {len(shards)}")
    for i, (name, data) in enumerate(shards):
        digest = shard_sha_override if (shard_sha_override and i == 0) else sha(data)
        lines.append(f"shard erbc.v1/{name} {len(data)} {digest}")
    return "\n".join(lines) + "\n"


def build_apk(
    path: Path,
    *,
    sharded: bool,
    drop: set[str] | None = None,
    shard_sha_override: str | None = None,
    break_manifest_sha: bool = False,
    extra_file: str | None = None,
    legacy: bool = False,
) -> Path:
    container = bytes(range(256)) * 40                       # 10 KiB 整容器
    meta = b'format-version 1\nprogram-sha256 "' + sha(container).encode() + b'"\nend\n'
    stmt_idx = b"ERSTMT01" + b"\x00" * 32
    if sharded:
        third = len(container) // 3
        parts = [
            ("program.part000.erbc", container[:third]),
            ("program.part001.erbc", container[third:2 * third]),
            ("program.part002.erbc", container[2 * third:]),
        ]
        parts_manifest = "".join(f"{n}\t{len(d)}\n" for n, d in parts).encode()
    else:
        parts = None
        parts_manifest = b""

    text = manifest_text(
        container=container, meta=meta, stmt_idx=stmt_idx, parts=parts,
        shard_sha_override=shard_sha_override, drop=drop, legacy=legacy,
    ).encode()
    if parts is not None:
        # 清单里的 program.parts 占位换成真实字节（sha/字节数必须按真实内容算）
        text = text.replace(
            f"package-artifact erbc.v1/program.parts 0 {sha(b'')}".encode(),
            f"package-artifact erbc.v1/program.parts {len(parts_manifest)} {sha(parts_manifest)}".encode(),
        )

    entries: list[tuple[str, bytes]] = [
        ("classes.dex", b"dex\n035\x00" + b"\x00" * 64),
        ("assets/CSV/Abl.csv", b"a,b\n1,2\n"),
        ("assets/resources/a.webp", b"RIFF\x00\x00\x00\x00WEBP"),
        ("assets/sound/a.mp3", b"ID3\x03\x00\x00\x00"),
        ("assets/plugins/a.xml", b"<root/>"),
        ("assets/emuera.config", b"GAME_TITLE \"x\"\n"),
        (ASSET + "program.meta", meta),
        (ASSET + "program.stmt.idx", stmt_idx),
        (ASSET + "manifest.txt", text),
    ]
    if sharded:
        assert parts is not None
        entries += [(ASSET + n, d) for n, d in parts]
        entries.append((ASSET + "program.parts", parts_manifest))
    else:
        entries.append((ASSET + "program.erbc", container))
    if extra_file:
        entries.append((ASSET + extra_file, b"stray"))

    # package.report 的随包口径：staged_scope = erbc.v1/*（除 report）+ CSV/resources/sound/plugins + emuera.config
    in_scope = [
        (n, d) for n, d in entries
        if n != inspect_apk.REPORT_ENTRY and inspect_apk.staged_scope(n)
    ]
    staged_bytes = sum(len(d) for _, d in in_scope)
    report = "\n".join([
        "schema eratw-package-report",
        "version 1",
        "program-mode stored",
        "program-chunk-mb 1",
        f"program-parts {len(parts) if parts else 0}",
        f"manifest-sha256 {'0' * 64 if break_manifest_sha else sha(text)}",
        f"staged-entries {len(in_scope)}",
        f"staged-bytes {staged_bytes}",
        "extensionless-files 0",
        "linked-files 0",
        "copied-files 0",
        "no-compress-suffixes csv,erbc,meta,mp3,parts,xml,webp",
        "align-slack-bytes 0",
        f"apk-ceiling-bytes {staged_bytes + 1024 * 1024}",
        "game-root /tmp/game",
        "erbc-source /tmp/erbc",
    ]) + "\n"
    entries.append((ASSET + "package.report", report.encode()))

    path.parent.mkdir(parents=True, exist_ok=True)
    with zipfile.ZipFile(path, "w", compression=zipfile.ZIP_STORED) as zf:
        for name, data in entries:
            zf.writestr(name, data)
    return path


def run(apk: Path, require_bundled: bool = False):
    return inspect_apk.check(apk, False, False, require_bundled, 1000)


def main() -> int:
    try:
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    except Exception:      # noqa: BLE001 - 老终端不支持 reconfigure 也不该影响断言
        pass
    failures: list[str] = []

    def expect(name: str, rep, *, ok: bool, needle: str = "") -> None:
        passed = (not rep.fails) if ok else bool(rep.fails)
        if passed and needle:
            passed = any(needle in f for f in rep.fails)
        print(f"{'PASS' if passed else 'FAIL'}  {name}")
        if not passed:
            failures.append(name)
            for line in rep.lines:
                print("      " + line)
        elif ok:
            for line in rep.lines:
                if "清单" in line or "分片汇总" in line or "manifest-sha256" in line:
                    print("      " + line)

    with tempfile.TemporaryDirectory() as tmp:
        root = Path(tmp)
        expect("单条：清单与随包文件集双向一致", run(build_apk(root / "single.apk", sharded=False)), ok=True)
        expect("分片：shard 汇总 = container-artifact", run(build_apk(root / "shard.apk", sharded=True)), ok=True)
        expect(
            "红：包里多一个清单没登记的文件",
            run(build_apk(root / "extra.apk", sharded=False, extra_file="program.stray")),
            ok=False, needle="没登记",
        )
        expect(
            "红：清单漏登记 program.meta",
            run(build_apk(root / "drop.apk", sharded=False, drop={"program.meta"})),
            ok=False, needle="没登记",
        )
        expect(
            "红：package.report 的 manifest-sha256 对不上",
            run(build_apk(root / "badsha.apk", sharded=False, break_manifest_sha=True)),
            ok=False, needle="manifest-sha256",
        )
        expect(
            "红：分片 sha 被改坏（汇总也不等）",
            run(build_apk(root / "badshard.apk", sharded=True, shard_sha_override="f" * 64)),
            ok=False, needle="SHA-256",
        )
        expect(
            "红：旧格式清单在 --require-bundled 下不可对账",
            run(build_apk(root / "legacy.apk", sharded=False, legacy=True), require_bundled=True),
            ok=False, needle="旧格式",
        )

    print()
    if failures:
        print(f"{len(failures)} 条用例失败：{failures}")
        return 1
    print("全部通过")
    return 0


if __name__ == "__main__":
    sys.exit(main())
